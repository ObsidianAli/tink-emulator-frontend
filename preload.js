const { contextBridge, ipcRenderer, webFrame } = require('electron');

contextBridge.exposeInMainWorld('tink', {
  getSetup: () => ipcRenderer.invoke('getSetup'),
  pickExe: (id) => ipcRenderer.invoke('pickExe', id),
  pickFolder: (id) => ipcRenderer.invoke('pickFolder', id),
  clearFolder: (id) => ipcRenderer.invoke('clearFolder', id),
  finishSetup: (covers) => ipcRenderer.invoke('finishSetup', covers),
  getSettings: () => ipcRenderer.invoke('getSettings'),
  setFullscreen: (on) => ipcRenderer.invoke('setFullscreen', on),
  setHeart: (mode) => ipcRenderer.invoke('setHeart', mode),
  setLeftEdge: (mode) => ipcRenderer.invoke('setLeftEdge', mode),
  setFocusStyle: (mode) => ipcRenderer.invoke('setFocusStyle', mode),
  setBackground: (mode) => ipcRenderer.invoke('setBackground', mode),
  setKeyboard: (mode) => ipcRenderer.invoke('setKeyboard', mode),
  setIconStyle: (mode) => ipcRenderer.invoke('setIconStyle', mode),
  setSounds: (picked) => ipcRenderer.invoke('setSounds', picked),
  setIconRow: (mode) => ipcRenderer.invoke('setIconRow', mode),
  setHomeProfiles: (on) => ipcRenderer.invoke('setHomeProfiles', on),
  setSteamKey: (key) => ipcRenderer.invoke('setSteamKey', key),
  findAutomatically: (id) => ipcRenderer.invoke('findAutomatically', id),
  redownloadCovers: () => ipcRenderer.invoke('redownloadCovers'),
  logError: (text) => ipcRenderer.invoke('logError', text),
  getProfiles: () => ipcRenderer.invoke('getProfiles'),
  getAvatars: () => ipcRenderer.invoke('getAvatars'),
  chooseProfile: (id) => ipcRenderer.invoke('chooseProfile', id),
  addProfile: () => ipcRenderer.invoke('addProfile'),
  saveProfile: (edit) => ipcRenderer.invoke('saveProfile', edit),
  removeProfile: (id) => ipcRenderer.invoke('removeProfile', id),
  toggleFavourite: (id) => ipcRenderer.invoke('toggleFavourite', id),
  hideGame: (id) => ipcRenderer.invoke('hideGame', id),
  toggleConsole: (id) => ipcRenderer.invoke('toggleConsole', id),
  setSort: (sort) => ipcRenderer.invoke('setSort', sort),
  showGame: (key) => ipcRenderer.invoke('showGame', key),
  showHiddenGames: () => ipcRenderer.invoke('showHiddenGames'),
  getLibrary: () => ipcRenderer.invoke('getLibrary'),
  refreshLibrary: () => ipcRenderer.invoke('refreshLibrary'),
  getCover: (id) => ipcRenderer.invoke('getCover', id),
  getGameInfo: (id) => ipcRenderer.invoke('getGameInfo', id),
  getNews: (cachedOnly) => ipcRenderer.invoke('getNews', cachedOnly === true),
  getNewsImage: (id) => ipcRenderer.invoke('getNewsImage', id),
  markNewsSeen: () => ipcRenderer.invoke('markNewsSeen'),
  getUpdate: () => ipcRenderer.invoke('getUpdate'),
  checkForUpdates: () => ipcRenderer.invoke('checkForUpdates'),
  applyUpdate: () => ipcRenderer.invoke('applyUpdate'),
  getNotice: () => ipcRenderer.invoke('getNotice'),
  power: (action) => ipcRenderer.invoke('power', action),
  launch: (id) => ipcRenderer.invoke('launch', id),
  getOwnedGames: () => ipcRenderer.invoke('getOwnedGames'),
  installGame: (appId) => ipcRenderer.invoke('installGame', appId),
  getInstallProgress: (appId) => ipcRenderer.invoke('getInstallProgress', appId),
  findPcGames: () => ipcRenderer.invoke('findPcGames'),
  getFileIcon: (exe) => ipcRenderer.invoke('getFileIcon', exe),
  listFolder: (dir) => ipcRenderer.invoke('listFolder', dir),
  addPcGame: (entry) => ipcRenderer.invoke('addPcGame', entry),
  removePcGame: (id) => ipcRenderer.invoke('removePcGame', id),
  onGame: (callback) => {
    const listener = (_event, state, info) => callback(state, info);
    ipcRenderer.on('game', listener);
    return () => ipcRenderer.removeListener('game', listener);
  },
  handoffReady: () => ipcRenderer.invoke('handoffReady'),
  cancelLaunch: () => ipcRenderer.invoke('cancelLaunch'),
  focusGame: () => ipcRenderer.invoke('focusGame'),
  getAlbum: () => ipcRenderer.invoke('getAlbum'),
  getThumb: (id) => ipcRenderer.invoke('getThumb', id),
  getShot: (id) => ipcRenderer.invoke('getShot', id),
  deleteShot: (id) => ipcRenderer.invoke('deleteShot', id),
  learnScreenshotButton: () => ipcRenderer.invoke('learnScreenshotButton'),
  clearScreenshotButton: () => ipcRenderer.invoke('clearScreenshotButton'),
  onShot: (callback) => {
    const listener = () => callback();
    ipcRenderer.on('shot', listener);
    return () => ipcRenderer.removeListener('shot', listener);
  },
  releaseCaches: () => webFrame.clearCache(),
});
